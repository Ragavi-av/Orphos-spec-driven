package io.orphos.eip.setup.service;

import com.fasterxml.jackson.databind.ObjectMapper;
import io.orphos.eip.setup.dto.SetupDtos.AiConfig;
import io.orphos.eip.setup.dto.SetupDtos.AiProviderConn;
import io.orphos.eip.setup.dto.SetupDtos.ExternalDb;
import io.orphos.eip.setup.dto.SetupDtos.ExternalPostgres;
import io.orphos.eip.setup.dto.SetupDtos.FirstTenant;
import io.orphos.eip.setup.dto.SetupDtos.InstallPlan;
import io.orphos.eip.setup.dto.SetupDtos.InstallResult;
import io.orphos.eip.setup.dto.SetupDtos.Secrets;
import io.orphos.eip.setup.dto.SetupDtos.SetupConfig;
import org.springframework.stereotype.Service;

import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardCopyOption;
import java.time.Instant;
import java.util.List;
import java.util.StringJoiner;

/**
 * Turns a validated {@link SetupConfig} into the two artifacts the layered
 * Compose bring-up consumes: a {@code .env} (flags + secrets, projected into the
 * shape the infra/app compose files already read) and {@code orphos.config.json}
 * (the full, structured record — the single source of truth the wizard owns).
 *
 * <p>An existing {@code .env} is never silently clobbered: it is copied to
 * {@code .env.bak.<epochMillis>} first so a re-run is safe and reversible.</p>
 */
@Service
public class ConfigWriter {

    private final ObjectMapper json;
    private final Path targetDir;
    private final AiCatalog aiCatalog;

    public ConfigWriter(ObjectMapper json, AiCatalog aiCatalog, SetupPaths paths) {
        this.json = json;
        this.aiCatalog = aiCatalog;
        this.targetDir = paths.targetDir();
    }

    public InstallResult write(SetupConfig config, Secrets effectiveSecrets, InstallPlan plan) {
        try {
            Files.createDirectories(targetDir);

            Path envPath = targetDir.resolve(".env");
            String backup = null;
            if (Files.exists(envPath)) {
                Path bak = targetDir.resolve(".env.bak." + Instant.now().toEpochMilli());
                Files.copy(envPath, bak, StandardCopyOption.COPY_ATTRIBUTES);
                backup = bak.toString();
            }

            String envContent = renderEnv(config, effectiveSecrets);
            Files.writeString(envPath, envContent, StandardCharsets.UTF_8);

            // orphos.config.json carries the config with the effective secrets
            // merged in, so it is a faithful record of what was installed.
            SetupConfig persisted = new SetupConfig(
                    config.instanceName(), config.instanceSlug(), config.primaryDomain(),
                    config.demoMode(), config.bundledArcade(), config.bundledPostgres(),
                    config.arcade(), config.postgres(),
                    effectiveSecrets, plan.functionalities(), config.ai(), config.firstTenant());
            Path configPath = targetDir.resolve("orphos.config.json");
            Files.writeString(configPath,
                    json.writerWithDefaultPrettyPrinter().writeValueAsString(persisted),
                    StandardCharsets.UTF_8);

            return new InstallResult(true,
                    "Wrote .env and orphos.config.json to " + targetDir,
                    envPath.toString(), configPath.toString(), backup, plan);
        } catch (Exception e) {
            return new InstallResult(false, "Failed to write config: " + e.getMessage(),
                    null, null, null, plan);
        }
    }

    // ── .env rendering ──────────────────────────────────────────────────────

    private String renderEnv(SetupConfig c, Secrets s) {
        StringBuilder b = new StringBuilder(2048);
        b.append("# Generated by orphos-setup on ").append(Instant.now()).append("\n");
        b.append("# Instance: ").append(nz(c.instanceName())).append(" (").append(nz(c.instanceSlug())).append(")\n");
        b.append("# One-time values (secrets, DB choice) are locked to the initialized volumes —\n");
        b.append("# rotate them through the guarded flow, not by editing this file.\n\n");

        section(b, "Deployment profile");
        kv(b, "DEMO_MODE", Boolean.toString(c.demoMode()));

        section(b, "Bundled vs external databases");
        // ArcadeDB and Keycloak's Postgres are independent. EIP_BUNDLED_DB (legacy
        // master) is true only when both are bundled.
        // Infisical: bundled (own eip-infisical-db) unless it shares Keycloak's
        // Postgres or points at an explicit external URI.
        String infisicalUri = resolveInfisicalUri(c, s);
        boolean bundledInfisicalDb = infisicalUri == null;
        kv(b, "EIP_BUNDLED_ARCADEDB", Boolean.toString(c.bundledArcade()));
        kv(b, "EIP_BUNDLED_POSTGRES", Boolean.toString(c.bundledPostgres()));
        kv(b, "EIP_BUNDLED_INFISICAL_DB", Boolean.toString(bundledInfisicalDb));
        kv(b, "EIP_BUNDLED_DB", Boolean.toString(c.bundledArcade() && c.bundledPostgres() && bundledInfisicalDb));
        if (!c.bundledArcade() && c.arcade() != null) {
            ExternalDb a = c.arcade();
            b.append("# External ArcadeDB is the platform datastore (bundled ArcadeDB is off).\n");
            b.append("# Every app service points here via ARCADEDB_URL/USER; ARCADEDB_PASSWORD below\n");
            b.append("# is this server's root password. Per-tenant DEDICATED connections are still\n");
            b.append("# managed separately in the DB Connections admin screen.\n");
            kv(b, "ARCADEDB_URL", nz(a.url()).trim());
            kv(b, "ARCADEDB_USER", nz(a.user()).isBlank() ? "root" : a.user().trim());
        }
        // External Postgres for Keycloak (independent of the ArcadeDB choice).
        if (!c.bundledPostgres() && c.postgres() != null && notBlank(c.postgres().kcJdbcUrl())) {
            ExternalPostgres pg = c.postgres();
            kv(b, "KC_DB_URL", pg.kcJdbcUrl().trim());
            kv(b, "KC_DB_USERNAME", nz(pg.kcUser()));
            kv(b, "KC_DB_PASSWORD", nz(pg.kcPassword()));
        }
        // Infisical DB connection — shared-with-Keycloak (derived) or explicit external URI.
        if (infisicalUri != null) {
            kv(b, "INFISICAL_DB_CONNECTION_URI", infisicalUri);
        }

        section(b, "Security — one-time secrets");
        kv(b, "KEYCLOAK_ADMIN_PASSWORD", s.keycloakAdminPassword());
        // With bundled off, the external ArcadeDB already has a root password —
        // use it so app services authenticate to that server. Otherwise the
        // generated/reused secret initializes the bundled ArcadeDB.
        String arcadePw = (!c.bundledArcade() && c.arcade() != null && notBlank(c.arcade().password()))
                ? c.arcade().password() : s.arcadedbPassword();
        kv(b, "ARCADEDB_PASSWORD", arcadePw);
        // Bundled Postgres password — separate from ArcadeDB so they rotate independently.
        kv(b, "POSTGRES_PASSWORD", s.postgresPassword());
        kv(b, "FUSEKI_ADMIN_PASSWORD", s.fusekiAdminPassword());
        kv(b, "EIP_INTERNAL_SERVICE_TOKEN", s.internalServiceToken());

        section(b, "Infisical (secrets backend)");
        kv(b, "INFISICAL_ENCRYPTION_KEY", s.infisicalEncryptionKey());
        kv(b, "INFISICAL_AUTH_SECRET", s.infisicalAuthSecret());
        kv(b, "INFISICAL_ADMIN_PASSWORD", s.infisicalAdminPassword());
        // Password for Infisical's own bundled Postgres (eip-infisical-db). Only
        // meaningful when that container is bundled; the external URI carries its
        // own credentials.
        kv(b, "INFISICAL_DB_PASSWORD", s.infisicalDbPassword());

        section(b, "AI models");
        AiConfig ai = c.ai();
        if (ai != null) {
            String mode = nz(ai.localModelMode()).isBlank() ? "SINGLE" : ai.localModelMode().trim().toUpperCase();
            kv(b, "OLLAMA_MODEL_MODE", mode);
            if ("MULTIPLE".equals(mode)) {
                kv(b, "OLLAMA_EXTRA_MODELS", join(ai.extraModels()));
            } else {
                kv(b, "OLLAMA_SINGLE_MODEL", nz(ai.singleModel()));
            }
            // Each configured external provider writes its own catalogue-defined
            // API-key + model env vars — not hardcoded to Gemini/Anthropic.
            if (ai.providers() != null) {
                for (AiProviderConn conn : ai.providers()) {
                    if (conn == null) continue;
                    AiCatalog.ProviderDef def = aiCatalog.providerByKey(conn.provider());
                    if (def == null || !notBlank(conn.apiKey())) continue;
                    kv(b, def.apiKeyEnv(), conn.apiKey().trim());
                    String model = notBlank(conn.model()) ? conn.model().trim() : def.defaultModel();
                    if (notBlank(model)) kv(b, def.modelEnv(), model);
                }
            }
        }

        section(b, "First tenant (seeded from instance identity)");
        FirstTenant t = c.firstTenant();
        if (t != null) {
            kv(b, "EIP_TENANT_DEMO_DISPLAY_NAME", nz(t.displayName()));
            kv(b, "EIP_TENANT_DEMO_DOMAIN", nz(t.domain()));
            // Always provision the tenant; the flag below governs whether the
            // sample/demo dataset is loaded on top (clean tenant when false).
            kv(b, "EIP_TENANT_DEMO_BOOTSTRAP_ENABLED", "true");
            kv(b, "EIP_TENANT_SEED_SAMPLE_DATA", Boolean.toString(t.loadDemoData()));
            // The operator's chosen admin credentials become the real login for
            // the first tenant: platform-core's DemoTenantBootstrap seeds this
            // user (email + password) with the 'admin' role in the tenant realm,
            // and PlatformAdminBootstrap mirrors it with 'platform_admin' in the
            // separate 'platform' realm — so this one identity is BOTH the tenant
            // admin and the cross-tenant platform admin. Left blank, both realms
            // fall back to their bootstrap-grade defaults (admin/admin and pa/pa).
            if (notBlank(t.adminEmail())) {
                kv(b, "EIP_TENANT_ADMIN_EMAIL", t.adminEmail().trim());
            }
            if (notBlank(t.adminPassword())) {
                kv(b, "EIP_TENANT_ADMIN_PASSWORD", t.adminPassword());
            }
        }

        return b.toString();
    }

    private static void section(StringBuilder b, String title) {
        b.append("\n# ── ").append(title).append(" ").append("─".repeat(Math.max(0, 60 - title.length()))).append("\n");
    }

    private static void kv(StringBuilder b, String key, String value) {
        b.append(key).append('=').append(value == null ? "" : value).append('\n');
    }

    private static String join(List<String> xs) {
        if (xs == null || xs.isEmpty()) return "";
        StringJoiner j = new StringJoiner(",");
        xs.forEach(j::add);
        return j.toString();
    }

    private static String nz(String s) {
        return s == null ? "" : s;
    }

    private static boolean notBlank(String s) {
        return s != null && !s.isBlank();
    }

    /**
     * The Infisical DB connection URI, or null when Infisical uses its own bundled
     * Postgres. When {@code postgres.shareKeycloak} is set, Infisical reuses
     * Keycloak's Postgres: the bundled {@code eip-postgres} container (with the
     * bundled Postgres password) or the external Keycloak Postgres host (derived
     * from KC_DB_URL), always in a separate {@code infisical} database.
     */
    private static String resolveInfisicalUri(SetupConfig c, io.orphos.eip.setup.dto.SetupDtos.Secrets s) {
        ExternalPostgres pg = c.postgres();
        if (pg == null) return null;
        if (pg.shareKeycloak()) {
            if (c.bundledPostgres()) {
                return "postgres://postgres:" + nz(s.postgresPassword()) + "@eip-postgres:5432/infisical";
            }
            String hostPort = jdbcHostPort(pg.kcJdbcUrl());
            if (hostPort == null) return null;
            return "postgres://" + nz(pg.kcUser()) + ":" + nz(pg.kcPassword()) + "@" + hostPort + "/infisical";
        }
        return notBlank(pg.infisicalUri()) ? pg.infisicalUri().trim() : null;
    }

    /** Extracts {@code host:port} from a {@code jdbc:postgresql://host:port/db} URL. */
    private static String jdbcHostPort(String jdbc) {
        if (jdbc == null) return null;
        int i = jdbc.indexOf("://");
        if (i < 0) return null;
        String rest = jdbc.substring(i + 3);
        int slash = rest.indexOf('/');
        return (slash >= 0 ? rest.substring(0, slash) : rest).trim();
    }

    public String targetDir() {
        return targetDir.toString();
    }
}
