export const SUPPORTED_LANGUAGES = [
  { code: 'en', label: 'English',  nativeLabel: 'English' },
  { code: 'ja', label: 'Japanese', nativeLabel: '日本語'  },
];

// Pristine snapshot of the built-in catalog, taken before i18next.init().
// i18next's ResourceStore aliases the `resources` object we pass to init(), and
// applyLabelOverrides() calls addResourceBundle(..., overwrite=true), which
// reassigns store.data[code].translation. That mutation would otherwise leak
// back into `resources`, corrupting the "default" values shown in the Branding
// tab. getBaseCatalog reads from this frozen copy so defaults stay pristine.
const PRISTINE_RESOURCES = JSON.parse(JSON.stringify(resources));

// ── Tenant label overrides ─────────────────────────────────────────────
// Admins can rename any UI text per tenant + language from the Branding tab.
// BrandingProvider fetches the overrides with the active bundle and calls
// applyLabelOverrides(); the base catalog above always stays pristine so
// removing an override falls back to the built-in default.

const flattenCatalog = (obj, prefix = '', out = {}) => {
  for (const [k, v] of Object.entries(obj || {})) {
    const key = prefix ? `${prefix}.${k}` : k;
    if (v && typeof v === 'object') flattenCatalog(v, key, out);
    else out[key] = String(v);
  }
  return out;
};

const setPath = (obj, dottedKey, value) => {
  const parts = dottedKey.split('.');
  let node = obj;
  for (let i = 0; i < parts.length - 1; i++) {
    // Refuse to descend through a leaf (e.g. override "lang.label.x" when
    // "lang.label" is a string) — that would corrupt the catalog shape.
    if (typeof node[parts[i]] === 'string') return;
    node = node[parts[i]] = node[parts[i]] || {};
  }
  node[parts[parts.length - 1]] = value;
};

/** Flat {'copilot.title': 'AI Copilot', ...} view of the built-in catalog for a language. */
export function getBaseCatalog(lng) {
  const base = PRISTINE_RESOURCES[lng]?.translation || PRISTINE_RESOURCES.en.translation;
  return flattenCatalog(base);
}

/**
 * Layer tenant overrides on top of the built-in catalog and re-render, in
 * EVERY bundle on the page.
 *
 * The apply itself is `applyLabelOverridesLocal`; this wrapper adds the
 * cross-bundle broadcast so a remote's catalog gets the tenant's labels too —
 * without it, only whichever bundle BrandingProvider happens to run in saw
 * them (the same federation duplication described at the language bridge).
 *
 * @param labelsByLang {en: {'copilot.title': '...'}, ja: {...}} — flat dotted keys.
 */
export function applyLabelOverrides(labelsByLang) {
  applyLabelOverridesLocal(labelsByLang);
  if (typeof window !== 'undefined' && !(window[BRIDGE_KEY] || {}).applying) {
    try {
      window.dispatchEvent(new CustomEvent(LABELS_EVENT, { detail: { labels: labelsByLang } }));
    } catch { /* no CustomEvent — this bundle's catalog is still updated */ }
  }
}

/** Apply overrides to THIS bundle's catalog only. */
function applyLabelOverridesLocal(labelsByLang) {
  for (const { code } of SUPPORTED_LANGUAGES) {
    // Rebuild from the pristine base every time so removing an override falls
    // back to the built-in default. Cloning from the live `resources` would
    // retain stale overrides (addResourceBundle does a full replace below).
    const merged = JSON.parse(JSON.stringify(PRISTINE_RESOURCES[code].translation));
    for (const [key, value] of Object.entries(labelsByLang?.[code] || {})) {
      if (typeof value === 'string' && value.trim() !== '') setPath(merged, key, value);
    }
    // deep=false replaces the whole bundle — merged is already complete.
    i18n.addResourceBundle(code, 'translation', merged, false, true);
    for (const inst of scopedInstances) {
      inst.addResourceBundle(code, 'translation', merged, false, true);
    }
  }
  // Re-emitting languageChanged makes every useTranslation() consumer re-render.
  i18n.changeLanguage(i18n.language);
  for (const inst of scopedInstances) inst.changeLanguage(inst.language);
}

// ── Scoped language instances ──────────────────────────────────────────
// A screen can own an independent language choice by rendering its tree
// inside <I18nextProvider i18n={createScopedI18n('orphos.<area>.lang')}>.
// The scoped instance shares the resource catalog (and keeps receiving
// tenant label overrides via applyLabelOverrides), but its active language
// is detected and persisted under its own localStorage key, so switching
// it never touches the global 'orphos.lang' choice — and vice versa.
// Deliberately NOT .use(initReactI18next): that would replace the default
// instance every useTranslation() outside a provider resolves to.
const scopedInstances = [];

export function createScopedI18n(storageKey) {
  const instance = i18n.createInstance();
  instance
    .use(LanguageDetector)
    .init({
      // Own pristine copy of the catalog so bundle swaps on one instance can
      // never bleed into the other's resource store.
      resources: JSON.parse(JSON.stringify(PRISTINE_RESOURCES)),
      fallbackLng: 'en',
      supportedLngs: ['en', 'ja'],
      nonExplicitSupportedLngs: true,
      interpolation: { escapeValue: false },
      detection: {
        order: ['localStorage', 'navigator'],
        lookupLocalStorage: storageKey,
        caches: ['localStorage'],
      },
    });
  scopedInstances.push(instance);
  return instance;
}

