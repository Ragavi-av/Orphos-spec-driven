// Merge a flat {'a.b.c': 'text'} table into one language's nested catalog.
// Throws on a key whose path collides with an existing leaf (e.g. adding
// 'tasks.scope.all' when 'tasks.scope' is already a string) — silently dropping
// it would leave the UI showing a raw key with no clue why.
const mergeFlatCatalog = (lng, table) => {
  const root = resources[lng].translation;
  for (const [dotted, value] of Object.entries(table)) {
    const parts = dotted.split('.');
    let node = root;
    for (let i = 0; i < parts.length - 1; i++) {
      if (typeof node[parts[i]] === 'string') {
        throw new Error(`i18n: "${dotted}" collides with leaf "${parts.slice(0, i + 1).join('.')}"`);
      }
      node = node[parts[i]] = node[parts[i]] || {};
    }
    node[parts[parts.length - 1]] = value;
  }
};

