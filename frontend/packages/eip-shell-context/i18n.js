// ── Cross-bundle language bridge ───────────────────────────────────────
// Module Federation gives the host AND every remote its own copy of this
// module — see any remote's dist/assets/__federation_shared_eip-shell-context
// chunk, and the bundling note in widgets/src/RemoteApp.jsx. So
// `i18n.changeLanguage()` from the shell's LanguageSwitcher only ever moved the
// SHELL's instance: the widget board, the co-pilot and every other remote kept
// rendering in whatever language their own copy detected at init, and caught up
// only on a full page reload. That is the "switching needs a hard refresh" bug.
//
// `window` is the one thing all those bundles genuinely share, so the switch is
// broadcast over it: every copy of this module registers its instance in a
// window-level registry and listens for the event, so a switch anywhere moves
// every instance on the page.
//
// `changeLanguage` is PATCHED rather than replaced by a new export, so every
// existing call site keeps working — the shell's LanguageSwitcher,
// BrandingProvider's tenant-default apply, and any remote calling
// `i18n.changeLanguage()` off its own useTranslation() all broadcast for free.
const BRIDGE_KEY = '__orphosI18nBridge';
const LANG_EVENT = 'orphos:languagechange';
const LABELS_EVENT = 'orphos:labeloverrides';

const bridge = (() => {
  if (typeof window === 'undefined') return null;   // SSR / unit tests
  if (!window[BRIDGE_KEY]) {
    window[BRIDGE_KEY] = { instances: new Set(), applying: false };
  }
  return window[BRIDGE_KEY];
})();

/**
 * Register an instance for cross-bundle fan-out and make its own
 * changeLanguage broadcast.
 *
 * `bridge.applying` breaks the echo: instances driven BY a broadcast must not
 * each rebroadcast, or two bundles ping-pong the same switch forever.
 */
function bridgeInstance(instance) {
  if (!bridge || instance.__orphosBridged) return instance;
  instance.__orphosBridged = true;
  bridge.instances.add(instance);

  const native = instance.changeLanguage.bind(instance);
  instance.changeLanguage = (lng, ...rest) => {
    const result = native(lng, ...rest);
    if (!bridge.applying && lng) {
      try {
        window.dispatchEvent(new CustomEvent(LANG_EVENT, { detail: { lng } }));
      } catch { /* no CustomEvent — the local switch still applied */ }
    }
    return result;
  };
  return instance;
}

/** Drive every registered instance to `lng`, without re-broadcasting. */
function fanOutLanguage(lng) {
  if (!bridge || !lng) return;
  bridge.applying = true;
  try {
    for (const inst of bridge.instances) {
      // Compare on the base tag: an instance already resolved to 'ja' must not
      // be re-switched by a 'ja-JP' broadcast, which would re-render the whole
      // page for nothing.
      if ((inst.language || '').split('-')[0] !== String(lng).split('-')[0]) {
        inst.changeLanguage(lng);
      }
    }
  } finally {
    bridge.applying = false;
  }
}

if (bridge) {
  // Only the global instance is bridged. Scoped instances (createScopedI18n)
  // own an independent language on purpose — see the note above them.
  bridgeInstance(i18n);

  window.addEventListener(LANG_EVENT, (event) => {
    if (!bridge.applying) fanOutLanguage(event?.detail?.lng);
  });

  // Other tabs of the same workspace. LanguageDetector persists the choice to
  // localStorage and `storage` fires only in the OTHER tabs, so this keeps a
  // second window in step without either tab reloading.
  window.addEventListener('storage', (event) => {
    if (event.key === 'orphos.lang' && event.newValue) fanOutLanguage(event.newValue);
  });

  // Tenant label overrides have the same one-bundle-only problem: the shell
  // applied them to its own catalog while every remote kept the built-in
  // defaults. Re-applying per bundle is idempotent (addResourceBundle replaces
  // the bundle wholesale), so a plain rebroadcast is enough.
  window.addEventListener(LABELS_EVENT, (event) => {
    if (bridge.applying) return;
    bridge.applying = true;
    try {
      applyLabelOverridesLocal(event?.detail?.labels || {});
    } finally {
      bridge.applying = false;
    }
  });
}

