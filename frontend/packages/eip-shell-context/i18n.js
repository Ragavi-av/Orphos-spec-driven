// ── "Did the reader pick this language, or did we?" ────────────────────
// LanguageDetector caches EVERY changeLanguage() to 'orphos.lang', including
// the tenant-default apply — so the presence of that key says nothing about who
// chose. The distinction matters: the tenant's primary country supplies a
// DEFAULT language, and a reader who picked one from the header must keep it
// when the country changes or the branding bundle is refetched. So an explicit
// pick sets its own marker, and only that marker counts as a reader choice.
const LANG_CHOICE_KEY = 'orphos.lang.explicit';

/** Record that the READER chose the current language (LanguageSwitcher). */
export function markLanguageChosen() {
  try { localStorage.setItem(LANG_CHOICE_KEY, '1'); } catch { /* not fatal */ }
}

/** True when the reader has picked a language, so no default may override it. */
export function hasChosenLanguage() {
  try { return localStorage.getItem(LANG_CHOICE_KEY) === '1'; } catch { return false; }
}

/** Drop the reader's pick, returning them to the tenant country's default. */
export function clearLanguageChoice() {
  try { localStorage.removeItem(LANG_CHOICE_KEY); } catch { /* not fatal */ }
}

